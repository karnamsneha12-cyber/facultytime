export function getFacultyById(id: string): Faculty | undefined {
  return FACULTIES.find(f => f.id === id);
}

export function getFacultyByName(name: string): Faculty | undefined {
  return FACULTIES.find(f => f.name.toLowerCase() === name.toLowerCase());
}

export function getSubjectsForFaculty(facultyId: string): string[] {
  const faculty = getFacultyById(facultyId);
  return faculty ? faculty.subjects : [];
}

export function getTimetableForFaculty(facultyId: string): TimetableEntry[] {
  return TIMETABLE_ENTRIES.filter(e => e.faculty_id === facultyId || e.facultyId === facultyId);
}

export function getSectionsForFacultyAndSubject(facultyId: string, subject: string): string[] {
  const entries = TIMETABLE_ENTRIES.filter(
    e => (e.faculty_id === facultyId || e.facultyId === facultyId) && 
         (e.subject.toLowerCase() === subject.toLowerCase() || 
          subject.toLowerCase().includes(e.subject.toLowerCase()) || 
          e.subject.toLowerCase().includes(subject.toLowerCase()))
  );
  const sections = Array.from(new Set(entries.map(e => e.section)));
  return sections;
}

export function getTodayDayName(): DayOfWeek {
  const days: DayOfWeek[] = ['Sunday' as any, 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
  const dayIndex = new Date().getDay();
  if (dayIndex === 0) return 'Monday';
  return days[dayIndex] || 'Monday';
}

export function getTodayClassesForFaculty(facultyId: string, dayOverride?: DayOfWeek): TimetableEntry[] {
  const day = dayOverride || getTodayDayName();
  return TIMETABLE_ENTRIES
    .filter(e => (e.faculty_id === facultyId || e.facultyId === facultyId) && e.day === day)
    .sort((a, b) => a.startMinutes - b.startMinutes);
}

export function getAllSectionsForDay(section: 'CSM-A' | 'CSM-B', day: DayOfWeek): TimetableEntry[] {
  return TIMETABLE_ENTRIES
    .filter(e => e.section === section && e.day === day)
    .sort((a, b) => a.startMinutes - b.startMinutes);
}
